export function ensureSocialCatalogue(project){
 if(project&&!project.social)project.social=structuredClone(DEFAULT_SOCIAL_CATALOG);
 return project;
}
export const SOCIAL_GUEST_KEYS={10001:'zombie',10003:'sans',10004:'minion',10005:'coffee',10006:'returningZombie'};
export function socialImageURL(value){
 return typeof value==='string'&&(/^(\.\/)?media\/[\w./-]+$/.test(value)||/^https:\/\//.test(value)||/^data:image\/(png|jpeg|webp|gif);base64,[A-Za-z0-9+/=]+$/.test(value))?value:'';
}
export function socialMatches(post,visit){
 if(!post.enabled||post.kind!=='guest'||SOCIAL_GUEST_KEYS[post.guestId]!==visit.guestId||visit.skipped||visit.outcome==='tutorialSkipped')return false;
 if(post.branch&&post.branch!=='any'&&post.branch!==((visit.returnBranch||visit.branch)==='employed'?'job':visit.returnBranch||visit.branch))return false;
 const failed=typeof visit.beautySuccess==='boolean'?!visit.beautySuccess:Number.isFinite(visit.score)?visit.score<40:visit.reviewKind==='battle';
 return post.outcome==='any'||(post.outcome==='beauty'&&!failed)||(post.outcome==='failure'&&failed)||(post.outcome==='battle'&&failed&&['victory','forcedWin','offerWin'].includes(visit.outcome));
}
export function socialPost(template,visit=null){
 const composite=template.kind==='guest'&&template.imageMode==='composite',result=template.imageMode==='result';
 return {...template,day:visit?Math.max(template.day,visit.day):template.day,id:template.id+(visit?'@'+visit.id:''),guest:visit?.guestId,kind:visit?(template.outcome==='beauty'?'beauty':'battle'):null,
  user:template.user||'작성자 미지정',photo:template.imageMode==='none'?null:result?socialImageURL(visit?.portrait):socialImageURL(template.image),
  wholePortrait:!composite,portrait:composite?socialImageURL(visit?.headPortrait):null,avatar:socialImageURL(template.avatar),draft:false};
}
export function socialReviewPost(visit,catalog,day=visit.day){
 const templates=catalog?.posts||[];
 // A branch-specific review overrides the shared version, rather than producing duplicates.
 const candidates=templates.filter(p=>p.day<=day&&socialMatches(p,visit)).sort((a,b)=>(a.branch==='any')-(b.branch==='any')||a.order-b.order);
 return candidates.length?socialPost(candidates[0],visit):null;
}
export function socialFeedPosts(run){
 const catalog=run.social||DEFAULT_SOCIAL_CATALOG;
 return [...catalog.posts.filter(p=>p.enabled&&p.kind==='world'&&p.day<=run.day).map(p=>socialPost(p)),
 ...(run.visits||[]).filter(v=>v.day<=run.day).map(v=>socialReviewPost(v,catalog,run.day)).filter(Boolean)]
 .sort((a,b)=>b.day-a.day||a.order-b.order);
}
export function socialPreviewRecords(catalog,day,result='beauty',branch='job'){
 const seen=new Set();return catalog.posts.filter(p=>p.kind==='guest'&&p.day<=day).flatMap(p=>{
  const key=p.day+':'+p.guestId;if(seen.has(key))return [];seen.add(key);
  return [{id:p.guestId,day:p.day,name:p.title,score:result==='beauty'?100:0,outcome:result==='beauty'?'beauty':'victory',forced:result!=='beauty',returnBranch:branch,gain:0,before:0,after:0}];
 });
}
export function socialCatalogueProblems(catalog){
 if(!catalog)return [];
 if(!Array.isArray(catalog.posts))return ['몬스타그램 게시글 목록이 올바르지 않습니다.'];
 const ids=new Set(),errors=[];
 for(const p of catalog.posts){
  if(!p||typeof p.id!=='string'||!p.id||ids.has(p.id)){errors.push('몬스타그램 게시글 ID를 확인해 주세요.');continue;}ids.add(p.id);
  if(!Number.isFinite(p.order)||!['none','image','result','composite'].includes(p.imageMode))errors.push('몬스타그램 표시 설정 확인: '+p.id);
  if(!Number.isInteger(p.day)||p.day<0||p.day>4||!['world','guest'].includes(p.kind)||typeof p.text!=='string'||!Array.isArray(p.choices)||!Array.isArray(p.comments))errors.push('몬스타그램 게시글 설정 확인: '+p.id);
  if(p.kind==='guest'&&!SOCIAL_GUEST_KEYS[p.guestId])errors.push('몬스타그램 손님 ID 확인: '+p.id);
  if(!['any','beauty','failure','battle'].includes(p.outcome)||!['any','job','lottery'].includes(p.branch))errors.push('몬스타그램 노출 분기 확인: '+p.id);
  for(const field of ['image','avatar'])if(p[field]&&!socialImageURL(p[field]))errors.push('몬스타그램 이미지 주소 확인: '+p.id);
 }
 return errors;
}
